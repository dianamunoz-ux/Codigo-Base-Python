def analizar_token(cadena):
    cadena = cadena.strip()
    if not cadena:
        return "Cadena vacía"

    # Conjunto de palabras reservadas comunes
    palabras_reservadas = {'if', 'else', 'while', 'for', 'return', 'def', 'class', 'import', 'from', 'true', 'false'}
    operadores = {'+', '-', '*', '/', '=', '<', '>', '%'}

    estado = 0
    i = 0

    while i < len(cadena):
        c = cadena[i]
        if estado == 0:
            if c.isalpha() or c == '_':
                # Estado 1: Posible palabra reservada o identificador simple (solo letras/guion bajo)
                estado = 1
            elif c.isdigit():
                estado = 2  # Estado para Número (Entero)
            elif c in operadores:
                estado = 4  # Estado para Operador
            else:
                return "No válido / Desconocido"
        elif estado == 1:
            if not (c.isalnum() or c == '_'):
                return "Token no válido"
            # Transiciona al Estado 5 (Identificador con números) si aparece un dígito
            if c.isdigit():
                estado = 5
        elif estado == 5:
            if not (c.isalnum() or c == '_'):
                return "Identificador no válido"
        elif estado == 2:
            if c == '.':
                estado = 3  # Transición a número decimal
            elif not c.isdigit():
                return "Número no válido"
        elif estado == 3:
            if not c.isdigit():
                return "Número decimal no válido"
        elif estado == 4:
            return "Operador no válido (demasiados caracteres)"
        i += 1

    # Clasificación final según el estado en el que terminó
    if estado == 1:
        if cadena.lower() in palabras_reservadas:
            return "Palabra reservada válida"
        return "Identificador válido"
    elif estado == 5:
        return "Identificador válido"
    elif estado in (2, 3):
        return "Número válido"
    elif estado == 4:
        return "Operador válido"
    return "Cadena no válida"

# --- Pruebas ---
entradas = ["if", "while", "variable1", "125", "45.67", "+", "_contador", "99num", "++"]
for e in entradas:
    print(f"'{e}' -> {analizar_token(e)}")
